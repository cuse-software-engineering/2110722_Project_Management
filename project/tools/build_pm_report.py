"""Build the 2110722 Software Project Management report of the CTRS project (Milestone 1).

1. Expand, in place, every `<!-- include: <path>#<section> [attrs] -->` … `<!-- /include -->` block of the
   milestone files with the quoted artifact section (same directive syntax and expander as the group report,
   assignments/group/tools/build_report.py) and every `<!-- finance: <table> -->` … `<!-- /finance -->` block with
   the table generated by tools/finance.py.
2. Render each milestone file to PDF with assignments/group/tools/build_pdf.py (TH Sarabun, Chula header,
   TOC with page numbers), with the cover, course and lecturer of 2110722.

Usage:  python3 tools/build_pm_report.py [--milestone 1] [--no-pdf]
Output: build/2110722_M1_part1_genai_log.pdf, build/2110722_M1_part2_final_deliverables.pdf
"""
import argparse
import html
import re
import sys
from pathlib import Path

PM = Path(__file__).resolve().parent.parent            # workspace/project-management
REPO = PM.parent.parent
GROUP_TOOLS = REPO / "assignments" / "group" / "tools"
sys.path.insert(0, str(GROUP_TOOLS))
sys.path.insert(0, str(PM / "tools"))
import build_report                                     # noqa: E402  (include expander of the group report)
import build_pdf                                        # noqa: E402  (PDF renderer of the group report)
import finance                                          # noqa: E402

COURSE = "2110722 Software Project Management"
LECTURER = "Assoc. Prof. Twittie Senivongse"
TITLE = "Concert Table Reservation System (CTRS) for La Loy Restaurant"
FILES = {  # milestone -> [(source markdown, output stem, subtitle)]
    1: [(PM / "milestone1" / "part1-genai-log.md", "2110722_M1_part1_genai_log", "Milestone 1 · Part 1 GenAI Log"),
        (PM / "milestone1" / "part2-final-deliverables.md", "2110722_M1_part2_final_deliverables",
         "Milestone 1 · Part 2 Final Deliverables: business case, financial analysis, project charter, project organization")],
}
INCLUDE_RE = re.compile(r"^<!--\s*include:\s*(.+?)\s*-->\s*\n.*?^<!--\s*/include\s*-->", re.S | re.M)
FINANCE_RE = re.compile(r"^<!--\s*finance:\s*(\w+)\s*-->\s*\n.*?^<!--\s*/finance\s*-->", re.S | re.M)


def finance_blocks() -> dict[str, str]:
    text, _ = finance.tables()
    return {m.group(1): m.group(2).strip() for m in re.finditer(r"<!-- (\w+) -->\n(.*?)\n<!-- /\1 -->", text, re.S)}


def drop_columns(lines: list[str], names: list[str]) -> list[str]:
    """Remove the columns whose header cell equals one of `names` from every pipe table of the block."""
    out, idx = [], None
    for line in lines:
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if idx is None:                      # header row of a table
                idx = [i for i, c in enumerate(cells) if c in names]
            if idx:
                cells = [c for i, c in enumerate(cells) if i not in idx]
                out.append("| " + " | ".join(cells) + " |"); continue
        else:
            idx = None
        out.append(line)
    return out


def flatten(lines: list[str]) -> list[str]:
    """A section quoted from the Part 2 report into a GenAI log record: nested include/finance markers removed
    (the text between them stays), headings and table captions demoted to bold lines (no TOC or list entries,
    no duplicate anchors), figure captions dropped (the figures stay in Part 2), landscape pages disabled."""
    out = []
    for l in lines:
        t = l.strip()
        if t.startswith(("<!-- include:", "<!-- /include", "<!-- finance:", "<!-- /finance")):
            continue
        if t.startswith("<!-- source:") and out and out[-1].strip().startswith("<!-- source:"):
            continue
        if m := re.match(r"#{1,6} (.*)", l):
            l = f"**{m.group(1)}**"
        elif m := re.match(r"\*(Table [0-9A-Z]+\.\d+ .*)\*\s*$", l):
            l = f"**{m.group(1)}**"
        elif re.match(r"\*Figure [0-9A-Z]+\.\d+ .*\*\s*$", l):
            continue
        l = l.replace(' landscape"', '"').replace('class="landscape ', 'class="')
        out.append(l)
    return out


def keep_columns(lines: list[str], idx: list[int]) -> list[str]:
    """Keep only the 1-based columns `idx`, in that order, of every pipe table of the block."""
    out = []
    for line in lines:
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if max(idx) > len(cells):
                raise SystemExit(f"keep={idx}: a row has only {len(cells)} column(s): {line[:60]}")
            out.append("| " + " | ".join(cells[i - 1] for i in idx) + " |"); continue
        out.append(line)
    return out


def rename_columns(lines: list[str], pairs: dict[str, str]) -> list[str]:
    """Rename the header cells of every pipe table of the block according to `pairs`."""
    out, header = [], True
    for line in lines:
        if line.startswith("|") and header:
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            out.append("| " + " | ".join(pairs.get(c, c) for c in cells) + " |"); header = False; continue
        if not line.startswith("|"):
            header = True
        out.append(line)
    return out


def split_id(lines: list[str], name: str) -> list[str]:
    """Split the column `name`, whose cells read '<ID>: <text>', into an ID column and a text column."""
    out, col = [], None
    for line in lines:
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if col is None:                      # header row
                col = cells.index(name)
                cells[col:col + 1] = ["ID", name]
            elif set(cells[col]) <= {"-", ":"}:  # separator row
                cells[col:col + 1] = ["---", "---"]
            else:
                ident, _, text = cells[col].partition(":")
                text = text.strip()
                cells[col:col + 1] = [ident.strip(), text[:1].upper() + text[1:]]
            out.append("| " + " | ".join(cells) + " |"); continue
        col = None
        out.append(line)
    return out


def expand_file(md: Path) -> None:
    text = md.read_text(encoding="utf-8")
    fin = finance_blocks()

    def inc(m):
        spec = m.group(1)
        drop = re.search(r"\s+drop=(\S+)", spec)            # PM-report attribute: drop the named columns of the quoted table
        keep = re.search(r"\s+keep=(\S+)", spec)            # PM-report attribute: keep only these 1-based columns, in this order
        split = re.search(r"\s+split=(\S+)", spec)          # PM-report attribute: split '<ID>: <text>' cells of the named column
        rename = re.search(r"\s+rename=(\S+)", spec)        # PM-report attribute: rename header cells, old:new[,old:new] (_ = space)
        flat = re.search(r"\s+flat\b", spec)                 # PM-report attribute: quote an already expanded report section as plain text
        block = build_report.expand(md, re.sub(r"\s+(drop|keep|split|rename)=\S+|\s+flat\b", "", spec))
        if flat:
            block = flatten(block)
        if drop:
            block = drop_columns(block, drop.group(1).split(","))
        if keep:
            block = keep_columns(block, [int(i) for i in keep.group(1).split(",")])
        if rename:
            pairs = dict(x.replace("_", " ").split(":") for x in rename.group(1).split(","))
            block = rename_columns(block, pairs)
        if split:
            block = split_id(block, split.group(1).replace("_", " "))
        return f"<!-- include: {spec} -->\n" + "\n".join(block) + "\n<!-- /include -->"

    def fn(m):
        if m.group(1) not in fin:
            raise SystemExit(f"{md.name}: unknown finance block '{m.group(1)}' (known: {', '.join(fin)})")
        return f"<!-- finance: {m.group(1)} -->\n\n{fin[m.group(1)]}\n\n<!-- /finance -->"

    new = INCLUDE_RE.sub(inc, text)
    new = FINANCE_RE.sub(fn, new)
    if new != text:
        md.write_text(new, encoding="utf-8")
    print(f"expanded {md.relative_to(REPO)}: {len(INCLUDE_RE.findall(new))} includes, {len(FINANCE_RE.findall(new))} finance tables")


_render_part = build_pdf.render_part


def render_part_with_lists(md_path: Path):
    """The group builder's render_part, plus a List of Tables and a List of Figures appended to the TOC (as in the
    course's sample report); the entries link to the caption anchors that crosslink() adds, so number_toc() gives
    them page numbers like the headings."""
    body, toc = _render_part(md_path)
    tabs = re.findall(r'<p class="tcap"><em>(Table ([0-9A-Z]+\.\d+)[^<]*)</em>', body)
    figs = re.findall(r'<p><em>(Figure ([0-9A-Z]+\.\d+)[^<]*)</em>', body)
    def lst(title, items, prefix):
        if len(items) < 3:                     # a one-line list page is not worth a page (the GenAI log)
            return ""
        lis = "".join(f'<li><a href="#{prefix}-{n}">{html.escape(text)}</a></li>' for text, n in items)
        return f'<h2 class="lot">{title}</h2><ul>{lis}</ul>'
    return body, toc + lst("List of Tables", tabs, "tab") + lst("List of Figures", figs, "fig")


build_pdf.render_part = render_part_with_lists


def make_cover(subtitle: str, version: str):
    def cover(_version, _parts):
        members = "".join(f'<tr><td>{n}</td><td class="id">Student ID {i}</td></tr>' for i, n in build_pdf.MEMBERS)
        return f"""<section class="cover">
<img class="emblem" src="{build_pdf.LOGO_EMBLEM.as_uri()}" alt="Chulalongkorn University">
<div class="title">{html.escape(TITLE)}</div>
<div class="subtitle">{html.escape(subtitle)}<br>{html.escape(COURSE)}</div>
<div class="lead">Submitted to</div>
<div class="lecturer">{html.escape(LECTURER)}</div>
<div class="members-title">Members</div>
<div class="group">{html.escape(build_pdf.GROUP_LINE)}</div>
<table>{members}</table>
<div class="version">Version {version} · September 2026<br>Software Engineering Program, Department of Computer Engineering, Faculty of Engineering, Chulalongkorn University · Semester 1, Academic Year 2569</div>
</section>"""
    return cover


def build(milestone: int, pdf: bool) -> None:
    files = [f for f in FILES[milestone] if f[0].exists() or print(f"skip {f[0].name}: not found")]
    for md, _, _ in reversed(files):          # Part 2 first: the GenAI log quotes its sections as final outputs
        expand_file(md)
    if not pdf:
        return
    for md, stem, subtitle in files:
        build_pdf.COURSE, build_pdf.LECTURER, build_pdf.DRAFT = COURSE, LECTURER, False
        if "hr.pagebreak" not in build_pdf.CSS:      # a `---` rule in the GenAI log starts a new page (one record per page)
            build_pdf.CSS += ("\nhr { border: 0; height: 0; margin: 0; page-break-after: always; } /* hr.pagebreak */"
                              "\ndiv.charter th:nth-child(1) { width: 20%; }"        # project charter: label column
                              "\ntable.uc td:first-child { width: 22%; }"
                              "\ntable.rec { border: 1pt solid #4b5563; }"                    # GenAI log record: Item | Content
                              "\ntable.rec > tbody > tr > td { border: 0.6pt solid #6b7280; padding: 5pt 8pt 6pt; vertical-align: top; }"
                              "\ntable.rec td.k { width: 16%; font-weight: bold; color: #0b2a4a; background: #eef2f7; }"
                              "\ntable.rec tr { page-break-inside: auto; break-inside: auto; }"
                              "\ntable.rec p { margin: 0 0 5pt; text-align: left; }"
                              "\ntable.rec ul, table.rec ol { margin: 0 0 5pt; padding-left: 18pt; }"
                              "\ntable.rec table { font-size: 10.5pt; line-height: 1.25; margin: 4pt 0 8pt; }"
                              "\ntable.rec table th, table.rec table td { padding: 2.5pt 4pt; }"
                              "\ntable.rec blockquote { margin: 2pt 0 6pt; padding: 3pt 10pt; border-left: 2.5pt solid #c9a227; background: #fafaf5; }"
                              "\ntable.rec blockquote p { margin: 0 0 3pt; }"
                              "\ntable.rec p.mat { margin-top: 8pt; padding-top: 6pt; border-top: 0.6pt dashed #9ca3af; }"
                              "\ntable.rec td img { max-height: 200mm; width: 100%; }"
                              "\n.keep:has(> table.rec) { break-inside: auto; page-break-inside: auto; }"
                              "\n.toc h2.lot { page-break-before: always; font-size: 24pt; color: #0b2a4a; margin: 0 0 12pt; padding-bottom: 6pt; border-bottom: 2.5pt solid #c9a227; }")
        build_pdf.cover = make_cover(subtitle, "1.0")
        build_pdf.build([md], "v1", PM / "build" / f"{stem}.pdf")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
